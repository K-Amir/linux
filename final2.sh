#!/usr/bin/env bash
# Hysteria 2 / QUIC UDP tuning and optional swap for Ubuntu/Debian.
# Does not change firewall rules, port hopping, NIC offloads, or TCP BBR.
# Safe to rerun. Does not restart services.
set -Eeuo pipefail

if (( EUID != 0 )); then
  echo 'Run as root: sudo bash hysteria2-optimize-fixed.sh' >&2
  exit 1
fi

for cmd in awk grep df findmnt sysctl swapon mkswap fallocate dd chmod rm \
           mkdir cp mv date; do
  if ! command -v "$cmd" >/dev/null 2>&1; then
    echo "Missing required command: $cmd" >&2
    exit 1
  fi
done

SYSCTL_FILE=/etc/sysctl.d/99-hysteria2.conf
OLD_SYSCTL_FILE=/etc/sysctl.d/99-xray.conf
SWAPFILE=/swapfile
STAMP=$(date +%Y%m%d-%H%M%S)
RAM_MB=$(awk '/^MemTotal:/ { printf "%d", $2 / 1024; exit }' /proc/meminfo)

if [[ ! "$RAM_MB" =~ ^[0-9]+$ ]] || (( RAM_MB < 64 )); then
  echo 'Cannot determine available physical RAM.' >&2
  exit 1
fi

if (( RAM_MB <= 2500 )); then
  DEFAULT_SWAP_MB=2048
  DEFAULT_SOCKET_BUFFER=262144   # 256 KiB
  NETDEV_BACKLOG=4096
  CONNTRACK_TARGET=131072
else
  DEFAULT_SWAP_MB=1024
  DEFAULT_SOCKET_BUFFER=524288   # 512 KiB
  NETDEV_BACKLOG=8192
  CONNTRACK_TARGET=262144
fi

# Override e.g. SWAP_SIZE_MB=512, or disable with SWAP_SIZE_MB=0.
REQUESTED_SWAP_MB=${SWAP_SIZE_MB:-$DEFAULT_SWAP_MB}
if [[ ! "$REQUESTED_SWAP_MB" =~ ^[0-9]+$ ]]; then
  echo 'SWAP_SIZE_MB must be a nonnegative integer (MiB).' >&2
  exit 1
fi

echo "Physical RAM: ${RAM_MB} MiB"

# Only create a NEW swapfile if no swap exists anywhere. Never overwrite an
# existing /swapfile; it may contain data or be owned by another tool.
create_swapfile() {
  local size_mb=$1
  local fstype
  fstype=$(findmnt -n -o FSTYPE -T / 2>/dev/null || true)

  if [[ "$fstype" == btrfs ]]; then
    if command -v btrfs >/dev/null 2>&1; then
      echo 'Btrfs detected; using btrfs filesystem mkswapfile.'
      if ! btrfs filesystem mkswapfile --size "${size_mb}m" "$SWAPFILE"; then
        rm -f -- "$SWAPFILE"
        return 1
      fi
    else
      echo 'Btrfs needs btrfs-progs for safe swapfile creation. Skipping.' >&2
      return 1
    fi
  else
    if ! fallocate -l "${size_mb}M" "$SWAPFILE" 2>/dev/null; then
      rm -f -- "$SWAPFILE"
      echo 'fallocate failed; attempting fully allocated dd fallback.'
      if ! dd if=/dev/zero of="$SWAPFILE" bs=1M count="$size_mb" \
              conv=fsync status=none; then
        rm -f -- "$SWAPFILE"
        return 1
      fi
    fi
    chmod 600 "$SWAPFILE"
    if ! mkswap "$SWAPFILE" >/dev/null; then
      rm -f -- "$SWAPFILE"
      return 1
    fi
  fi

  chmod 600 "$SWAPFILE"
  if ! swapon "$SWAPFILE"; then
    echo 'swapon failed: filesystem, quota or virtualization may disallow swap.' >&2
    rm -f -- "$SWAPFILE"
    return 1
  fi

  if ! grep -Eq '^[[:space:]]*/swapfile[[:space:]]+' /etc/fstab; then
    echo '/swapfile none swap sw 0 0' >> /etc/fstab
  fi
  return 0
}

if swapon --noheadings --show=NAME | grep -q '[^[:space:]]'; then
  echo 'Swap already active; no changes made.'
elif (( REQUESTED_SWAP_MB == 0 )); then
  echo 'Swap creation disabled (SWAP_SIZE_MB=0).'
elif [[ -e "$SWAPFILE" ]]; then
  echo "WARNING: $SWAPFILE exists but swap is not active. Leaving it untouched." >&2
else
  # Reserve at least 512 MiB free on the root volume, and choose a smaller
  # swapfile when the disk cannot fit the originally requested size.
  FREE_MB=$(df -Pm / | awk 'NR==2 {print $4}')
  if [[ ! "$FREE_MB" =~ ^[0-9]+$ ]]; then
    echo 'WARNING: Cannot read free disk space; skipping swap creation.' >&2
  else
    AVAILABLE_MB=$((FREE_MB - 512))
    ACTUAL_SWAP_MB=$REQUESTED_SWAP_MB
    if (( ACTUAL_SWAP_MB > AVAILABLE_MB )); then
      ACTUAL_SWAP_MB=$AVAILABLE_MB
    fi
    ACTUAL_SWAP_MB=$(( ACTUAL_SWAP_MB / 256 * 256 ))
    if (( ACTUAL_SWAP_MB < 256 )); then
      echo "WARNING: only ${FREE_MB} MiB free on /. Not enough room for safe swap." >&2
    else
      echo "Creating ${ACTUAL_SWAP_MB} MiB swapfile (free disk: ${FREE_MB} MiB)."
      if create_swapfile "$ACTUAL_SWAP_MB"; then
        echo 'Swap active and persisted in /etc/fstab.'
      else
        echo 'WARNING: swap creation failed; continuing with UDP tuning.' >&2
      fi
    fi
  fi
fi

# Disable only the recognizable sysctl file generated by the older uploaded
# Xray/VLESS script; leave any unrelated user-owned files unchanged.
if [[ -f "$OLD_SYSCTL_FILE" ]]; then
  if grep -Fq '# Auto-generated for' "$OLD_SYSCTL_FILE" && \
     grep -Fq '# Optimized for VLESS+Reality in censored environments' "$OLD_SYSCTL_FILE"; then
    mv "$OLD_SYSCTL_FILE" "${OLD_SYSCTL_FILE}.disabled-${STAMP}"
    echo 'Backed up and disabled the old VLESS/Reality sysctl profile.'
  else
    echo "NOTE: Existing $OLD_SYSCTL_FILE left untouched; check for conflicts." >&2
  fi
fi

mkdir -p /etc/sysctl.d
if [[ -e "$SYSCTL_FILE" ]]; then
  cp -a "$SYSCTL_FILE" "${SYSCTL_FILE}.backup-${STAMP}"
fi

# Linux buffers are maximum ALLOWANCES, not preallocated reservations.
# QUIC is UDP: TCP congestion parameters do not tune Hysteria's QUIC BBR.
cat > "$SYSCTL_FILE" <<EOF
# Hysteria 2 / QUIC UDP tuning; RAM ${RAM_MB} MiB
fs.file-max = 1000000
net.core.rmem_max = 16777216
net.core.wmem_max = 16777216
net.core.rmem_default = ${DEFAULT_SOCKET_BUFFER}
net.core.wmem_default = ${DEFAULT_SOCKET_BUFFER}
net.core.netdev_max_backlog = ${NETDEV_BACKLOG}
net.ipv4.udp_rmem_min = 16384
net.ipv4.udp_wmem_min = 16384
vm.swappiness = 10
EOF

# If connection tracking exists, increase a too-low maximum for NAT-based
# port hopping. Do not lower an existing higher limit.
if [[ -r /proc/sys/net/netfilter/nf_conntrack_max ]]; then
  CT_CURRENT=$(cat /proc/sys/net/netfilter/nf_conntrack_max)
  if [[ "$CT_CURRENT" =~ ^[0-9]+$ ]] && (( CT_CURRENT < CONNTRACK_TARGET )); then
    printf '\nnet.netfilter.nf_conntrack_max = %s\n' "$CONNTRACK_TARGET" >> "$SYSCTL_FILE"
  fi
fi

if ! sysctl -p "$SYSCTL_FILE"; then
  echo "WARNING: One or more sysctl values could not be applied. Inspect $SYSCTL_FILE." >&2
fi

# A systemd service also needs a NOFILE limit. Do not restart a running proxy.
if command -v systemctl >/dev/null 2>&1; then
  UNIT_CHANGED=0
  for UNIT in x-ui.service xray.service hysteria-server.service hysteria.service; do
    if [[ "$(systemctl show -p LoadState --value "$UNIT" 2>/dev/null || true)" == loaded ]]; then
      DIR="/etc/systemd/system/${UNIT}.d"
      mkdir -p "$DIR"
      cat > "${DIR}/zz-hysteria2-nofile.conf" <<'EOF'
[Service]
LimitNOFILE=131072
EOF
      echo "Set LimitNOFILE=131072 for $UNIT (effective after next restart)."
      UNIT_CHANGED=1
    fi
  done
  if (( UNIT_CHANGED )); then
    systemctl daemon-reload
  fi
fi

printf '\nHysteria 2 UDP tuning complete.\n'
printf 'Kernel settings: %s\n' "$SYSCTL_FILE"
sysctl net.core.rmem_max net.core.wmem_max net.core.netdev_max_backlog vm.swappiness || true
printf 'Swap status:\n'
swapon --show || true
printf 'No proxy services were restarted, and no firewall rules were changed.\n'
